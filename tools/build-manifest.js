// STAGE 4 — tier by vote_count percentile, generate decoys, emit data/movies.js for the game.
const fs = require('fs');
const path = require('path');
const C = require('./config');
const http = require('./lib/http');
const cache = require('./lib/cache');
const T = require('./lib/text');
const { parseArgs } = require('./lib/args');

const AUTH = { Authorization: 'Bearer ' + C.TMDB_BEARER, accept: 'application/json' };
const tmdb = (pathQuery) => http.getJSON(C.TMDB_BASE + pathQuery, { headers: AUTH, delayMs: C.delays.tmdbMs });

function tierFor(p) {
  for (const t of C.tiers) if (p >= t.min) return t.key;
  return 'cinephile';
}

async function discover(film, ladder) {
  const year = film.year || 2000;
  const p = new URLSearchParams({
    sort_by: 'vote_count.desc',
    'vote_count.gte': String(ladder.gte),
    'primary_release_date.gte': `${year - ladder.era}-01-01`,
    'primary_release_date.lte': `${year + ladder.era}-12-31`,
  });
  if (ladder.lte) p.set('vote_count.lte', String(ladder.lte));
  if (ladder.lang && film.original_language) p.set('with_original_language', film.original_language);
  if (ladder.genres && film.genreIds?.length) p.set('with_genres', film.genreIds.slice(0, ladder.gcount).join('|'));
  const r = await tmdb('/discover/movie?' + p.toString());
  return (r.results || []).filter((m) => m.id !== film.tmdbId && T.norm(m.title) !== T.norm(film.title));
}

async function buildDecoys(film) {
  const cacheP = path.join(C.paths.cache, 'discover', film.tmdbId + '.json');
  const cached = cache.readJSON(cacheP);
  if (cached && cached.length >= 3) return pick3(cached, film);

  const gte = film.vote_count < 200 ? C.decoys.obscureFloor : Math.max(C.decoys.voteFloor, Math.round(film.vote_count * C.decoys.voteFraction));
  const lte = Math.max(gte * 3, film.vote_count * C.decoys.voteCapMult);
  const ladders = [
    { gte, lte, era: C.decoys.eraBand, lang: true, genres: true, gcount: 2 },
    { gte, era: C.decoys.eraBand, lang: true, genres: true, gcount: 2 },
    { gte, era: 8, lang: true, genres: true, gcount: 2 },
    { gte, era: 8, lang: false, genres: true, gcount: 1 },
    { gte: 50, era: 12, lang: false, genres: false },
  ];
  let pool = [];
  for (const l of ladders) { pool = await discover(film, l); if (pool.length >= 3) break; }
  const titles = pool.map((m) => m.title);
  cache.writeJSON(cacheP, titles);
  return pick3(titles, film);
}

function pick3(titles, film) {
  const top = titles.slice(0, C.decoys.poolTop);
  const seen = new Set([T.norm(film.title)]);
  const out = [];
  while (out.length < 3 && top.length) {
    const i = Math.floor(Math.random() * top.length);
    const t = top.splice(i, 1)[0];
    const n = T.norm(t);
    if (!seen.has(n)) { seen.add(n); out.push(t); }
  }
  return out;
}

async function run(opts = {}) {
  fs.mkdirSync(path.join(C.paths.cache, 'discover'), { recursive: true });

  let films = cache.readJSON(C.paths.matched, []).filter((m) => (m.frames || []).length >= C.frames.min);
  if (!films.length) { console.error('No films with frames in matched.json — run earlier stages first.'); return; }

  // difficulty: percentile by vote_count (tiebreak vote_average)
  const sorted = [...films].sort((a, b) => (a.vote_count - b.vote_count) || (a.vote_average - b.vote_average));
  const n = sorted.length;
  sorted.forEach((f, i) => { f._p = n <= 1 ? 1 : i / (n - 1); f.difficulty = tierFor(f._p); });

  // decoys
  console.log(`Generating decoys for ${films.length} films…`);
  const out = [], dropped = [];
  let done = 0;
  for (const f of sorted) {
    done++;
    let decoys = [];
    try { decoys = await buildDecoys(f); } catch (e) { console.warn(`  decoy fail ${f.slug}: ${e.message}`); }
    if (decoys.length < 3) { dropped.push({ slug: f.slug, reason: 'fewer than 3 decoys' }); continue; }
    out.push({
      title: f.title,
      year: f.year,
      director: f.director,
      country: f.country,
      difficulty: f.difficulty,
      decoys,
      frames: f.frames,
    });
    if (done % 25 === 0 || films.length <= 30)
      console.log(`  [${done}/${films.length}] ${f.title} — ${f.difficulty} — decoys: ${decoys.join(', ')}`);
  }

  // stable order: by difficulty then title (game samples per-tier anyway)
  const tierOrder = { easy: 0, medium: 1, hard: 2, veryhard: 3, cinephile: 4 };
  out.sort((a, b) => (tierOrder[a.difficulty] - tierOrder[b.difficulty]) || a.title.localeCompare(b.title));

  // preserve placeholder once
  if (cache.exists(C.paths.manifest) && !cache.exists(C.paths.placeholder))
    fs.copyFileSync(C.paths.manifest, C.paths.placeholder);

  const counts = out.reduce((m, f) => ((m[f.difficulty] = (m[f.difficulty] || 0) + 1), m), {});
  const banner = `// AUTO-GENERATED by tools/build-manifest.js — do not edit by hand.\n` +
    `// ${out.length} films · ${JSON.stringify(counts)}\n`;
  const body = `const MOVIES = ${JSON.stringify(out, null, 2)};\n` +
    `if (typeof module !== "undefined") module.exports = MOVIES;\n`;
  fs.mkdirSync(path.dirname(C.paths.manifest), { recursive: true });
  fs.writeFileSync(C.paths.manifest, banner + body);

  console.log(`\nStage 4 done → ${path.relative(C.paths.root, C.paths.manifest)}`);
  console.log(`  ${out.length} films  ${JSON.stringify(counts)}`);
  if (dropped.length) console.log(`  dropped ${dropped.length} (insufficient decoys)`);
  return out;
}

if (require.main === module) {
  const a = parseArgs();
  run({}).catch((e) => { console.error(e); process.exit(1); });
}
module.exports = { run, tierFor };
